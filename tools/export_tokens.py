#!/usr/bin/env python3
"""
export_tokens.py — the site shares the map's theme: derive CSS tokens from the
same parameters build_style.py uses, and refuse to write tokens that would
break the project's own rules (R-07 text ≥4.5:1; graphical objects ≥3:1).

Writes site/src/styles/tokens.css and site/src/data/tokens.json.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
import build_style as b  # noqa: E402
import palette_audit as pa  # noqa: E402

ROOT = b.ROOT
WHITE = (255, 255, 255)


def hexify(rgb):
    return "#%02X%02X%02X" % tuple(int(round(v)) for v in rgb[:3])


def cr(a, bg=WHITE):
    return pa.contrast_ratio(pa.rel_luminance(a), pa.rel_luminance(bg))


def lstep(rgb, target):
    """Same hue/chroma as rgb, CIELAB L* adjusted to hit contrast `target` on white (±0.05)."""
    L, a, bb = pa.rgb_to_lab(rgb[:3])
    lo, hi = 0.0, 100.0
    for _ in range(60):
        mid = (lo + hi) / 2
        c = b.lab_to_rgb((mid, a, bb))
        if cr(c) > target:
            lo = mid
        else:
            hi = mid
    return b.lab_to_rgb((lo, a, bb))


def main():
    style = json.load(open(os.path.join(ROOT, "styles", "accessible-v0.json")))
    by = {l["id"]: l for l in style["layers"]}
    water_label = pa.parse_colour(by["All-Lake-Names"]["paint"]["text-color"])
    contour = pa.parse_colour(b.P["contour_index"])
    T = {
        "paper": "#FFFFFF",
        "ink": "#000000",                                  # Topo50 black ink
        "contour": b.P["contour_index"],                   # index contour
        "contour-light": b.P["contour_intermediate"],      # intermediate contour (decorative only)
        "water": hexify(water_label),                      # water-label blue: links
        "water-fill": "#B8DCF2",                           # LINZ lake fill
        "scrub": hexify(pa.parse_colour(b.P["scrub"])),
        "grid": "#008BCA",                                 # Topo50 grid / water ink, used faintly
        # Evidence-grade ramp for the Sankey: one hue (contour brown), lightness only,
        # every step ≥3:1 on paper (WCAG 1.4.11) and ≥1.4:1 from its neighbour.
        "grade-a": hexify(lstep(contour, 12.0)),
        "grade-b": hexify(lstep(contour, 7.0)),
        "grade-c": hexify(lstep(contour, 4.5)),
        "grade-d": hexify(lstep(contour, 3.1)),
    }
    checks = [("ink", 4.5), ("contour", 4.5), ("water", 4.5),
              ("grade-a", 3), ("grade-b", 3), ("grade-c", 3), ("grade-d", 3)]
    bad = []
    for k, floor in checks:
        v = cr(pa.parse_colour(T[k])[:3])
        if v < floor:
            bad.append(f"{k} {T[k]} is {v:.2f}:1 < {floor}")
    ramp = ["grade-a", "grade-b", "grade-c", "grade-d"]
    for x, y in zip(ramp, ramp[1:]):
        r = cr(pa.parse_colour(T[x])[:3], pa.parse_colour(T[y])[:3])
        if r < 1.4:
            bad.append(f"{x}/{y} only {r:.2f}:1 apart")
    if bad:
        print("TOKENS FAIL\n  " + "\n  ".join(bad))
        sys.exit(1)
    css = ["/* Generated by tools/export_tokens.py from the map style. Do not edit. */", ":root {"]
    css += [f"  --{k}: {v};" for k, v in T.items()]
    css.append("}")
    out = os.path.join(ROOT, "site", "src", "styles", "tokens.css")
    open(out, "w").write("\n".join(css) + "\n")
    json.dump(T, open(os.path.join(ROOT, "site", "src", "data", "tokens.json"), "w"), indent=1)
    for k, v in T.items():
        print(f"{k:13s}{v}  {cr(pa.parse_colour(v)[:3]):.2f}:1")


if __name__ == "__main__":
    main()
