def _road(text, line):
    return spec(text, (ROAD_FILL, CASE), line_mm=line)


def _black_line(text, line, source=LEGEND):
    return spec(text, (BLACK,), source=source, line_mm=line)


def _black_glyph(text, mark, stroke=None, source=LEGEND, colour=BLACK):
    return spec(text, (colour,), source=source, mark_mm=mark, stroke_mm=stroke)


def _keep_black_line(text, line=0.2):
    return spec(f"Keep the LINZ shape. {text}", (BLACK,), line_mm=line)


def _keep_black_glyph(text, mark=1.4, stroke=0.15):
    return spec(
        f"Keep the LINZ shape. {text}", (BLACK,), mark_mm=mark, stroke_mm=stroke
    )


