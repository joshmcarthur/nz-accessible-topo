def ink(hex_, name, role="carrier", on=None):
    return {"hex": hex_, "name": name, "role": role, "on": on}


def spec(text, inks=(), source=APPLIED, **sizes):
    out = {"text": text, "inks": list(inks), "source": source}
    for key in ("line_mm", "stroke_mm", "mark_mm", "exempt", "colour_only"):
        out[key] = sizes.get(key)
    return out


def sym(
    key,
    section,
    label,
    box,
    layer,
    status,
    measured,
    proposal=None,
    *,
    drawn="yes",
    merged_with=None,
    redrawn=False,
    note="",
):
    return {
        "key": key,
        "section": section,
        "label": label,
        "box": box,
        "layer": layer,
        "drawn": "merged" if merged_with else drawn,
        "merged_with": merged_with,
        "redrawn": redrawn,
        "status": status,
        "measured": measured,
        "proposal": proposal,
        "note": note,
    }


