import json
import os
import sys

from nzat.colour.contrast_ratio import contrast_ratio
from nzat.colour.lab_to_rgb import lab_to_rgb
from nzat.colour.parse_colour import parse_colour
from nzat.colour.rel_luminance import rel_luminance
from nzat.colour.rgb_to_lab import rgb_to_lab
from nzat.paths import ROOT
from nzat.style.load_rules import load_rules
from nzat.style.lookup_style_path import lookup_style_path

WHITE = (255, 255, 255)


def _hexify(rgb):
    red, green, blue = (int(round(v)) for v in rgb[:3])
    return f"#{red:02X}{green:02X}{blue:02X}"


def _cr(a, bg=WHITE):
    return contrast_ratio(rel_luminance(a), rel_luminance(bg))


def _lstep(rgb, target):
    """Same hue/chroma as rgb, CIELAB L* adjusted to hit contrast `target` on white (±0.05)."""
    L, a, bb = rgb_to_lab(rgb[:3])
    lo, hi = 0.0, 100.0
    for _ in range(60):
        mid = (lo + hi) / 2
        c = lab_to_rgb((mid, a, bb))
        if _cr(c) > target:
            lo = mid
        else:
            hi = mid
    return lab_to_rgb((lo, a, bb))


def main():
    rules = load_rules()
    style = json.load(open(os.path.join(ROOT, "styles", "accessible-v0.json")))
    by = {layer["id"]: layer for layer in style["layers"]}
    water_label = parse_colour(by["All-Lake-Names"]["paint"]["text-color"])
    contour = parse_colour(lookup_style_path(rules, "contours.index.colour"))
    T = {
        "paper": "#FFFFFF",
        "ink": "#000000",
        "contour": lookup_style_path(rules, "contours.index.colour"),
        "contour-light": lookup_style_path(rules, "contours.intermediate.colour"),
        "water": _hexify(water_label),
        "water-fill": "#B8DCF2",
        "scrub": lookup_style_path(rules, "vegetation.scrub.colour"),
        "grid": "#008BCA",
        "grade-a": _hexify(_lstep(contour, 12.0)),
        "grade-b": _hexify(_lstep(contour, 7.0)),
        "grade-c": _hexify(_lstep(contour, 4.5)),
        "grade-d": _hexify(_lstep(contour, 3.1)),
    }
    checks = [
        ("ink", 4.5),
        ("contour", 4.5),
        ("water", 4.5),
        ("grade-a", 3),
        ("grade-b", 3),
        ("grade-c", 3),
        ("grade-d", 3),
    ]
    bad = []
    for k, floor in checks:
        v = _cr(parse_colour(T[k])[:3])
        if v < floor:
            bad.append(f"{k} {T[k]} is {v:.2f}:1 < {floor}")
    ramp = ["grade-a", "grade-b", "grade-c", "grade-d"]
    for x, y in zip(ramp, ramp[1:], strict=False):
        r = _cr(parse_colour(T[x])[:3], parse_colour(T[y])[:3])
        if r < 1.4:
            bad.append(f"{x}/{y} only {r:.2f}:1 apart")
    if bad:
        print("TOKENS FAIL\n  " + "\n  ".join(bad))
        sys.exit(1)
    css = [
        "/* Generated by tools/export_tokens.py from the map style. Do not edit. */",
        ":root {",
    ]
    css += [f"  --{k}: {v};" for k, v in T.items()]
    css.append("}")
    out = os.path.join(ROOT, "site", "src", "styles", "tokens.css")
    open(out, "w").write("\n".join(css) + "\n")
    json.dump(
        T, open(os.path.join(ROOT, "site", "src", "data", "tokens.json"), "w"), indent=1
    )
    for k, v in T.items():
        print(f"{k:13s}{v}  {_cr(parse_colour(v)[:3]):.2f}:1")
