def queries_by_key():
    return {row["key"]: row for row in QUERIES}


def missing_symbol_keys():
    have = {row["key"] for row in QUERIES}
    want = {row["key"] for row in SYMBOLS}
    return sorted(want - have), sorted(have - want)
